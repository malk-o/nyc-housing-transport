# Search box -> fills the dropdowns (does not draw anything until Generate is pressed)
@app.callback(
    Output("borough", "value"), Output("year", "value"),
    Output("housing", "value"), Output("transport", "value"),
    Input("apply-search", "n_clicks"), State("search", "value"), prevent_initial_call=True)
def apply_search(_, text):
    p = parse_search(text, DF)
    return p["boroughs"], p["years"], p["housing"], p["transport"]


# Generate report -> updates ALL charts + KPIs at once
@app.callback(
    [Output(f"chart-{i}", "figure") for i in range(len(ALL_CHARTS))]
    + [Output("kpis", "children"), Output("status", "children")],
    Input("generate", "n_clicks"),
    State("borough", "value"), State("year", "value"),
    State("housing", "value"), State("transport", "value"))
def generate_report(_, boroughs, years, housing, transport):
    d = apply_filters(DF, boroughs, years, housing, transport)
    figs = []
    for title, fn in ALL_CHARTS:
        try:
            figs.append(style_fig(fn(d)) if len(d) else go.Figure())
        except Exception as e:  # one broken chart must not break the whole report
            figs.append(go.Figure().add_annotation(text=f"Chart error: {e}", showarrow=False))
    kpis = [html.Div(className="kpi", children=[html.B(f"{int(v):,}"), html.Span(k)]) for k, v in
            [("Rows (ZIP-months)", len(d)), (housing, d["housing_metric"].sum()),
             (transport, d["transport_metric"].sum()), ("ZIP codes", d["zip"].nunique())]]
    msg = (f"Report for {', '.join(b.title() for b in boroughs) if boroughs else 'all boroughs'}, "
           f"{', '.join(map(str, years)) if years else 'all years'}.")
    return figs + [kpis, msg]


