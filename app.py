from dash import Dash, dcc, html, Input, Output, State, ctx, no_update
import plotly.graph_objects as go

import charts_m1, charts_m2, charts_m3, charts_m4
from data_layer import (load_data, apply_filters, parse_search, BOROUGHS,
                        HOUSING_CATEGORIES, TRANSPORT_CATEGORIES)

DF = load_data()
YEARS = sorted(DF["year"].unique())
ALL_CHARTS = [c for m in (charts_m1, charts_m2, charts_m3, charts_m4) for c in m.CHARTS]

app = Dash(__name__, title="NYC: Building vs. Street Safety",
           external_stylesheets=["https://fonts.googleapis.com/css2?family=Public+Sans:wght@400;600;800&display=swap"])
server = app.server  # needed by gunicorn

PALETTE = ["#1f6f8b", "#d99100", "#c8442f", "#5b8c5a", "#7a5195"]


def style_fig(fig):
    fig.update_layout(template="plotly_white", colorway=PALETTE,
                      margin=dict(l=10, r=10, t=10, b=10), font=dict(family="Public Sans"),
                      legend=dict(orientation="h", y=-0.2))
    return fig


def card(i, title):
    wide = "card wide" if "map" in title.lower() or "overlap" in title.lower() else "card"
    return html.Div(className=wide, children=[
        html.H4(title), dcc.Loading(dcc.Graph(id=f"chart-{i}", config={"displaylogo": False}))])


def dd(label, id_, options, value, multi=False):
    return html.Div([html.Label(label), dcc.Dropdown(id=id_, options=options, value=value,
                                                     multi=multi, clearable=multi)])


